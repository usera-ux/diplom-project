  try {
    const { data, error } = await supabase
      .from('funds')
      .select('id, name, logo_url')

    if (error) throw error

    funds.value = (data || []).map(f => {
      let logo = null
      if (f.logo_url) {
        if (f.logo_url.startsWith('http')) {
          logo = f.logo_url
        } else {
          // Получаем публичный URL из Supabase Storage
          const { data: pub } = supabase.storage
            .from('funds')
            .getPublicUrl(f.logo_url)
          logo = pub?.publicUrl || null
        }
      }
      return { ...f, logo_url: logo }
    })
  } catch (err) {
    console.error('Ошибка загрузки фондов:', err)
    funds.value = []
  } finally {
    fundsLoading.value = false
  }
  if (item.value?.savedAt) {
    isSaved.value = true
    startReserveTimer(item.value.savedAt)
