function getReserveStatus() {
  if (!item.value?.savedAt) return null
  const elapsed = Math.floor((now.value - new Date(item.value.savedAt).getTime()) / 1000)
  return elapsed < 1 * 60 ? 'reserved' : 'sold'
}
const reserveExpired = ref(false)

function startReserveTimer(savedAt) {
  const created = new Date(savedAt).getTime()
  const total = 1 * 60

  const tick = () => {
    const elapsed = Math.floor((Date.now() - created) / 1000)
    reserveTimer.value = Math.max(total - elapsed, 0)
    
    if (reserveTimer.value <= 0) {
      clearInterval(reserveInterval)
      isSaved.value = false
      reserveExpired.value = true // 👈 помечаем что резерв истёк
      const raw = JSON.parse(localStorage.getItem('favorites') || '[]')
  const itemData = raw.find(i => String(i.id) === String(route.params.id))

  if (itemData) {
    addToPurchases(itemData, 'sold')
  }
    }
  }

  tick()
  reserveInterval = setInterval(tick, 1000)
}

const reserveTimerLabel = computed(() => {
  const s = reserveTimer.value
  const h = Math.floor(s / 3600)
  const m = Math.floor((s % 3600) / 60)
  const sec = s % 60
  return `${String(h).padStart(2,'0')}:${String(m).padStart(2,'0')}:${String(sec).padStart(2,'0')}`
})



function statusLabel(status) {
  const map = {
    review:    'На оценке',
    sold:      'Продан',
    unsold:    'Не продан',
    cancelled: 'Снят с продажи',
  }
  return map[status] ?? status
}
async function saveItem() {
  const raw = JSON.parse(localStorage.getItem('favorites') || '[]')
  const idx = raw.findIndex(i => String(i.id) === String(route.params.id))

  if (idx !== -1) {
    const chosenFund = funds.value.find(f => f.id === selectedFundId.value) || null
    const savedAt = new Date().toISOString()

    const updatedItem = {
      ...raw[idx],
      deliveryMethod: selectedDelivery.value?.name || raw[idx].deliveryMethod,
      soldAt: selectedDate.value || raw[idx].soldAt,
      isAnonymous: isAnonymous.value,
      fundId: chosenFund?.id || null,
      fundName: chosenFund?.name || null,
      fund: !!chosenFund,
      savedAt,
    }

    raw[idx] = updatedItem
    localStorage.setItem('favorites', JSON.stringify(raw))

    // 👇 ДОБАВЛЯЕМ В PURCHASES как reserved
    addToPurchases(updatedItem, 'reserved')

    isSaved.value = true
    startReserveTimer(savedAt)
  }
}
function deleteItem() {
  const raw = JSON.parse(localStorage.getItem('favorites') || '[]')
  const filtered = raw.filter(i => String(i.id) !== String(route.params.id))
  localStorage.setItem('favorites', JSON.stringify(filtered))
  router.back()
}
const showPriceSheet = ref(false)

const priceHistory = computed(() => {
  if (!item.value?.price) return []
  
  const basePrice = Number(item.value.price)
  const history = []
  
  // Генерируем историю на 4 недели назад
  const now = new Date()
  for (let i = 0; i < 2; i++) {
    const endDate = new Date(now)
    endDate.setDate(now.getDate() - i * 7)
    const startDate = new Date(endDate)
    startDate.setDate(endDate.getDate() - 6)

    const amount = Math.round(basePrice * Math.pow(0.9, i))

    const fmt = (d) => `${String(d.getDate()).padStart(2,'0')}.${String(d.getMonth()+1).padStart(2,'0')}.${d.getFullYear()}`

    history.push({
      dates: `${fmt(startDate)} - ${fmt(endDate)}`,
      amount,
    })
  }
  return history
})
function addToPurchases(itemData, status) {
  const raw = JSON.parse(localStorage.getItem('purchases') || '[]')

  const exists = raw.find(i => String(i.id) === String(itemData.id))

  const newItem = {
    ...itemData,
    purchaseStatus: status, // reserved | sold
    updatedAt: new Date().toISOString()
  }

  if (exists) {
    const updated = raw.map(i =>
      String(i.id) === String(itemData.id) ? newItem : i
    )
    localStorage.setItem('purchases', JSON.stringify(updated))
  } else {
    raw.push(newItem)
    localStorage.setItem('purchases', JSON.stringify(raw))
  }
}
