// Календарь
const currentMonthLabel = computed(() => {
  return calendarDate.value.toLocaleDateString('ru-RU', { month: 'long', year: 'numeric' })
})

const calendarDays = computed(() => {
  const d = new Date(calendarDate.value.getFullYear(), calendarDate.value.getMonth(), 1)
  const days = []
  // отступ — понедельник первый
  let startDay = d.getDay() === 0 ? 6 : d.getDay() - 1
  for (let i = 0; i < startDay; i++) days.push(null)
  while (d.getMonth() === calendarDate.value.getMonth()) {
    days.push(new Date(d))
    d.setDate(d.getDate() + 1)
  }
  return days
})

function prevMonth() {
  const d = new Date(calendarDate.value)
  d.setMonth(d.getMonth() - 1)
  calendarDate.value = d
}

function nextMonth() {
  const d = new Date(calendarDate.value)
  d.setMonth(d.getMonth() + 1)
  calendarDate.value = d
}

function isToday(day) {
  const t = new Date()
  return day.toDateString() === t.toDateString()
}

function isSelected(day) {
  return pendingDate.value && day.toDateString() === pendingDate.value.toDateString()
}

function isPast(day) {
  const t = new Date(); t.setHours(0,0,0,0)
  return day < t
}

function selectDay(day) {
  pendingDate.value = day
}

