let reserveInterval = null

// Фонды из Supabase
const funds        = ref([])
const fundsLoading = ref(true)


const now = ref(Date.now())
let ticker = null

// Способ передачи
const showDeliverySheet  = ref(false)
const selectedDelivery   = ref(null)
const deliveryMethods = ref([
  { id: 1, name: 'Курьером G2B', type: 'courier' },
  { id: 2, name: 'Самовывоз',    type: 'self' },
  { id: 3, name: 'Почта',        type: 'other' },
